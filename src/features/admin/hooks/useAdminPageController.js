    usersLoading,
    setUsersLoading,
    bills,
    setBills,
    dailySalesDate,
    setDailySalesDate,
    dailySalesLoading,
    setDailySalesLoading,
    dailySalesError,
    setDailySalesError,
    loading,
    setLoading,
    showProductForm,
    setShowProductForm,
    editingProduct,
    setEditingProduct,
    editingUser,
    setEditingUser,
    showUserForm,
    setShowUserForm,
    isCreatingUser,
    setIsCreatingUser,
    notification,
